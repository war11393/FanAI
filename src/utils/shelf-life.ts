/**
 * 根据到期时间计算剩余天数与健康状态。
 * 返回 'fresh' | 'expiring' | 'expired'，与后端规则一致。
 */
export function computeIngredientStatus(expireTime: string): 'fresh' | 'expiring' | 'expired' {
  const expire = new Date(expireTime).getTime();
  const now = Date.now();
  const oneDay = 24 * 60 * 60 * 1000;
  if (expire < now) return 'expired';
  if (expire - now <= oneDay) return 'expiring';
  return 'fresh';
}

export function remainingDays(expireTime: string): number {
  return Math.ceil((new Date(expireTime).getTime() - Date.now()) / (24 * 60 * 60 * 1000));
}